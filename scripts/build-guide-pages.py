#!/usr/bin/env python3
"""Build original guide content inside the shared reading and navigation frame."""
import json
from html import escape
from pathlib import Path
from string import Template
from site_components import LABELS,toolbar,pagination,utilities,dialogs,whatsapp,external_attrs,page_title
from guide_native import build_native
ROOT=Path(__file__).resolve().parents[1]


def e(value):return escape(str(value),quote=True)


def attrs(values):return ' '.join(f'{name}="{e(value)}"' for name,value in external_attrs(values).items())


def percentage_rect(rect,width,height):
 x,y,w,h=rect
 return f'left:{100*x/width:.6f}%;top:{100*y/height:.6f}%;width:{100*w/width:.6f}%;height:{100*h/height:.6f}%'


def compact_detail_title(image,title):
 x,y,w,h=title['rect'];wx,wy,ww,wh=title['word'];scale=title['scale']
 target_height=38 if any(key in image['src'] for key in ['-lixeira-','-luminaria-']) else 39
 scale=min(scale,target_height/wh)
 tw=ww*scale+32;th=wh*scale+16
 style=percentage_rect([x+w/2-tw/2,y+h/2-th/2,tw,th],image['width'],image['height'])
 cover_style=percentage_rect([x-3,y-3,w+6,h+6],image['width'],image['height'])
 blue_height=max(0,title['blue_end']-(y-3))
 cover=(f'<svg class="guide-title-cover" viewBox="{x-3} {y-3} {w+6} {h+6}" style="{cover_style}" aria-hidden="true">'
  f'<defs><linearGradient id="title-banner-gradient"><stop stop-color="{title["blue_left"]}"/><stop offset="1" stop-color="{title["blue_right"]}"/></linearGradient></defs>'
  f'<rect x="{x-3}" y="{y-3}" width="{w+6}" height="{h+6}" fill="{title["body_color"]}"/>'
  f'<rect x="{x-3}" y="{y-3}" width="{w+6}" height="{blue_height}" fill="url(#title-banner-gradient)"/></svg>')
 art=(f'<svg class="guide-title-art" data-title-scale="{scale}" viewBox="0 0 {tw} {th}" style="{style}" aria-hidden="true">'
  f'<rect x=".7" y=".7" width="{tw-1.4}" height="{th-1.4}" rx="{min(title["radius"]*scale,th/2)}" fill="white" stroke="#111" stroke-width="1.4"/>'
  f'<svg class="guide-title-word" x="16" y="8" width="{ww*scale}" height="{wh*scale}" viewBox="{wx} {wy} {ww} {wh}">'
  f'<image href="{e(image["src"])}" width="{title["width"]}" height="{title["height"]}"/></svg></svg>')
 return cover+art


def build():
 template=Template((ROOT/'templates/guide-page.html').read_text())
 pages=json.loads((ROOT/'data/guide-pages.json').read_text())
 photos=json.loads((ROOT/'data/apartment-photos.json').read_text())
 photo_upgrades=json.loads((ROOT/'data/guide-photo-upgrades.json').read_text())
 native_content=json.loads((ROOT/'data/guide-native-content.json').read_text())
 detail_titles=json.loads((ROOT/'data/detail-title-art.json').read_text())
 count=0
 for page in pages:
  image=page['image']
  if image['src'].endswith('-08.jpg'):continue  # Native shared section, generated by build-covers.py.
  native=next((value for suffix,value in native_content.items() if image['src'].endswith(suffix)),None)
  if native:
   (ROOT/page['path']).write_text(build_native(page,native,photo_upgrades,photos));count+=1
   continue
  lang=page['lang'];labels=LABELS[lang]
  back=page['back'] or {'href':page['home'],'label':labels['back']}
  back_html=f'<a class="site-back" href="{e(back["href"])}" aria-label="{e(back["label"])}">← <span>{e(back["label"].removeprefix("← "))}</span></a>'
  links=''.join(f'<a class="guide-link" {attrs(link)}></a>' for link in page['links'] if not(page['kind']=='detail' and link['href']==back['href']) and not(page.get('americanas') and link['href']==page['americanas']['href']))
  masks=''.join(f'<span class="guide-mask" aria-hidden="true" style="{percentage_rect(rect,image["width"],image["height"])}"></span>' for rect in page['masks'])
  americanas=''
  if page.get('americanas'):
   item=page['americanas'];americanas=f'<a class="guide-americanas" href="{e(item["href"])}" target="_blank" rel="noopener noreferrer" aria-label="{e(item["label"])}"><img src="/assets/brands/americanas.svg" alt="" width="163" height="32"/><span>LOJAS AMERICANAS</span></a>'
  upgraded=''
  if image['src'].endswith('-02.jpg'):
   photo=photos[0];variants=photo.get('variants',[])
   if variants:
    srcset=', '.join(f'{v["src"]} {v["width"]}w' for v in variants)
    upgraded=f'<img class="guide-photo-upgrade" src="{photo["src"]}" srcset="{srcset}" sizes="70vw" alt="" aria-hidden="true" width="{photo["width"]}" height="{photo["height"]}"/>'
  for suffix,photo in photo_upgrades.items():
   if image['src'].endswith(suffix):
    style=percentage_rect(photo['rect'],image['width'],image['height'])
    upgraded=f'<img class="guide-photo-upgrade" src="{e(photo["src"])}" alt="{e(photo["alt"][lang])}" width="{photo["width"]}" height="{photo["height"]}" style="{style};object-position:50% 50%" decoding="async"/>'
  if image['src'] in detail_titles:
   upgraded+=compact_detail_title(image,detail_titles[image['src']])
  output=template.substitute(lang=lang,title=e(page_title(lang,page['title'].rsplit(' — ',1)[-1])),description=e(page['description']),kind='guide-'+page['kind']+(' guide-information' if image['src'].endswith('-10.jpg') else ''),back=back_html,toolbar=toolbar(lang,page['languages']),utilities=utilities(lang),whatsapp=whatsapp(lang,page['path']),heading=f'<h1 class="guide-heading sr-only">{e(page["heading"])}</h1>' if page['heading'] else '',reading_label=labels['reading'],zoom_label=labels['zoom'],src=e(image['src']),alt=e(image['alt']),width=image['width'],height=image['height'],masks=masks,americanas=americanas,photo_upgrade=upgraded,links=links,pagination_label=labels['navigation'],pagination=pagination(lang,page['previous'],page['next']),source_text=page['source_text'],dialogs=dialogs(lang))
  (ROOT/page['path']).write_text('\n'.join(line.rstrip() for line in output.splitlines())+'\n');count+=1
 print(f'Generated {count} original guide sections with persistent navigation.')
if __name__=='__main__':build()
