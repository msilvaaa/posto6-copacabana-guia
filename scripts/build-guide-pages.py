#!/usr/bin/env python3
"""Build original guide content inside the shared reading and navigation frame."""
import json
from html import escape
from pathlib import Path
from string import Template
from site_components import LABELS,toolbar,pagination,utilities,dialogs,whatsapp,external_attrs
ROOT=Path(__file__).resolve().parents[1]


def e(value):return escape(str(value),quote=True)


def attrs(values):return ' '.join(f'{name}="{e(value)}"' for name,value in external_attrs(values).items())


def percentage_rect(rect,width,height):
 x,y,w,h=rect
 return f'left:{100*x/width:.6f}%;top:{100*y/height:.6f}%;width:{100*w/width:.6f}%;height:{100*h/height:.6f}%'


def build():
 template=Template((ROOT/'templates/guide-page.html').read_text())
 pages=json.loads((ROOT/'data/guide-pages.json').read_text())
 photos=json.loads((ROOT/'data/apartment-photos.json').read_text())
 count=0
 for page in pages:
  image=page['image']
  if image['src'].endswith('-08.jpg'):continue  # Native shared section, generated by build-covers.py.
  lang=page['lang'];labels=LABELS[lang]
  back=page['back'] or {'href':page['home'],'label':labels['back']}
  back_html=f'<a class="site-back" href="{e(back["href"])}" aria-label="{e(back["label"])}">← <span>{e(back["label"].removeprefix("← "))}</span></a>'
  links=''.join(f'<a class="guide-link" {attrs(link)}></a>' for link in page['links'] if not(page.get('americanas') and link['href']==page['americanas']['href']))
  masks=''.join(f'<span class="guide-mask" aria-hidden="true" style="{percentage_rect(rect,image["width"],image["height"])}"></span>' for rect in page['masks'])
  americanas=''
  if page.get('americanas'):
   item=page['americanas'];americanas=f'<a class="guide-americanas" href="{e(item["href"])}" target="_blank" rel="noopener noreferrer" aria-label="{e(item["label"])}"><img src="/assets/brands/americanas.svg" alt="" width="163" height="32"/><span>LOJAS AMERICANAS</span></a>'
  upgraded=''
  if image['src'].endswith('-02.jpg'):
   photo=photos[0];variants=photo.get('variants',[])
   if variants:
    srcset=', '.join(f'{v["src"]} {v["width"]}w' for v in variants)
    upgraded=f'<img class="guide-photo-upgrade" src="{photo["src"]}" srcset="{srcset}" sizes="70vw" alt="" aria-hidden="true" width="{photo["width"]}" height="{photo["height"]}"/>'
  output=template.substitute(lang=lang,title=e(page['title']),description=e(page['description']),kind='guide-'+page['kind'],back=back_html,toolbar=toolbar(lang,page['languages']),utilities=utilities(lang),whatsapp=whatsapp(lang),heading=f'<h1 class="guide-heading">{e(page["heading"])}</h1>' if page['heading'] else '',reading_label=labels['reading'],zoom_label=labels['zoom'],src=e(image['src']),alt=e(image['alt']),width=image['width'],height=image['height'],masks=masks,americanas=americanas,photo_upgrade=upgraded,links=links,pagination_label=labels['navigation'],pagination=pagination(lang,page['previous'],page['next']),source_text=page['source_text'],dialogs=dialogs(lang))
  (ROOT/page['path']).write_text('\n'.join(line.rstrip() for line in output.splitlines())+'\n');count+=1
 print(f'Generated {count} original guide sections with persistent navigation.')
if __name__=='__main__':build()
